export type CollectionImageAiPromptVars = {
  name: string
  slug: string
  url: string
}

export const COLLECTION_COVER_AI_PROMPT_KEY = 'collection_cover_ai_prompt'
export const COLLECTION_BANNER_AI_PROMPT_KEY = 'collection_banner_ai_prompt'

export const DEFAULT_COLLECTION_COVER_AI_PROMPT = `Ты — арт-директор каталога зарубежных сериалов.

Задача: напиши промпт для генерации ОБЛОЖКИ подборки «{name}» (соотношение сторон 4:3).

Контекст:
- Подборка: {name}
- Страница: {url}
- Формат: горизонтальная обложка каталога 4:3 (например 1200×900)
- Использование: плитка на /collections/

Требования к картинке:
- Атмосфера и визуальный язык темы подборки «{name}»
- Кинематографичный стиль зарубежных сериалов, без логотипов конкретных студий и без узнаваемых чужих постеров
- Крупный выразительный образ или сцена, читаемая в маленькой плитке
- Без текста, водяных знаков, UI, рамок и коллажа из нескольких кадров
- Высокая детализация, естественный свет, без «AI-артефактов» на лицах

Верни ТОЛЬКО готовый англоязычный image prompt (1–3 предложения), без пояснений до и после.`

export const DEFAULT_COLLECTION_BANNER_AI_PROMPT = `Ты — арт-директор каталога зарубежных сериалов.

Задача: напиши промпт для генерации ШИРОКОГО БАННЕРА подборки «{name}» (соотношение сторон 16:4).

Контекст:
- Подборка: {name}
- Страница: {url}
- Формат: широкий баннер 16:4 (например 1600×400)
- Использование: промо-блок на главной странице

Требования к картинке:
- Горизонтальная композиция с «воздухом» по краям (важное не у краёв — обрежется на мобильных)
- Атмосфера темы подборки «{name}», кинематографичный стиль зарубежных сериалов
- Без логотипов студий, без чужих постеров, без коллажа
- Без текста, водяных знаков и UI
- Высокая детализация, cinematic lighting

Верни ТОЛЬКО готовый англоязычный image prompt (1–3 предложения), без пояснений до и после.`

export function fillCollectionImageAiPrompt(
  template: string,
  vars: CollectionImageAiPromptVars,
): string {
  return template
    .replaceAll('{name}', vars.name)
    .replaceAll('{slug}', vars.slug)
    .replaceAll('{url}', vars.url)
    .trim()
}
